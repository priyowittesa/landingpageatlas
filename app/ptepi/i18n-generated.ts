const MONTHS_ID: Record<string, string> = { May: "Mei", Aug: "Agu", Oct: "Okt", Dec: "Des" };

/** Indonesian month abbreviations and "pts" in generated output. */
export function localiseUnits(text: string): string {
  return text
    .replace(/\b(May|Aug|Oct|Dec) (\d{4})\b/g, (_, m: string, y: string) => `${MONTHS_ID[m] ?? m} ${y}`)
    .replace(/(\d) pts\b/g, "$1 poin");
}

