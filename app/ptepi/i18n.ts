const SENTENCES = sentencePatterns((text) => translate(text, "id"));

/** A template that spans clauses ("; ") or sentences (". ") may match a joined text whole. */
function spansJoins(pattern: RegExp): boolean {
  return pattern.source.includes(";") || pattern.source.includes("\\. ");
}

function matchSentence(body: string, wholeOnly = false): string | null {
  for (const [pattern, build] of SENTENCES) {
    if (wholeOnly && !spansJoins(pattern)) continue;
    const match = pattern.exec(body);
    if (match) return build(match);
  }
  return null;
}

/** One clause: dictionary, then the sentence templates; unchanged when nothing matches. */
function translateClause(clause: string): string {
  const exact = ID[clause] ?? ID_GENERATED[clause] ?? INDONESIAN_SOURCE[clause];
  if (exact !== undefined) return exact;
  const withDot = ID[`${clause}.`] ?? ID_GENERATED[`${clause}.`];
  if (withDot !== undefined) return withDot.replace(/\.$/, "");
  return matchSentence(clause) ?? clause;
}

/**
 * Generated sentences (chart takeaways, reasons, captions, Nexa answers). A text made of
 * several sentences or ";"-joined clauses is split first, so a template for one clause
 * never swallows the next; templates written for the joined form are tried before that.
 */
function translateSentence(text: string): string {
  const trimmed = text.trim();
  const dot = trimmed.endsWith(".") ? "." : "";
  const body = dot ? trimmed.slice(0, -1) : trimmed;
  const joined = body.includes("; ") || body.includes(". ");
  const whole = matchSentence(body, joined);
  if (whole !== null) return localiseUnits(whole) + dot;
  const sentences = body.split(". ").map((sentence) => sentence.split("; ").map(translateClause).join("; "));
  const result = sentences.join(". ") + dot;
  return result === trimmed ? text : localiseUnits(result);
}

export function translate(text: string, language: Language): string {
  if (language === "en") return text;
  const exact = ID[text] ?? ID_GENERATED[text] ?? INDONESIAN_SOURCE[text];
  if (exact !== undefined) return exact;
  for (const [pattern, build] of PATTERNS) {
    const match = pattern.exec(text);
    if (match) return localiseUnits(build(match));
  }
  return translateSentence(text);
}

