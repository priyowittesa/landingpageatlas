"use client";

import { useState } from "react";
import Link from "next/link";
import { ArrowRight, Check, CircleCheck, MessageSquareText, Sparkles, UserCheck } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { DetailDrawer, DrawerSection } from "../../components/DetailDrawer";
import { ReasonText } from "../../components/ReasonText";
import { isListedInReason } from "../../components/reason-list";
import { Tr, useT } from "../../components/Tr";
import { formatDate } from "../../format";
import { AUTONOMY_LABELS } from "../../store/action-helpers";
import { useActionsStore, type EpiAction } from "../../store/actions-store";
import { OWNER_ROLES } from "../../store/roles";
import { SIGNAL_MODULES, type Signal } from "../signals";
import { Chip, KindChip, LevelChip, TagChips } from "./SignalRow";

type SignalDrawerProps = {
  signal: Signal | null;
  tracked: EpiAction | undefined;
  onClose: () => void;
  onOpenTracker: () => void;
};

/**
 * The detail of one signal and what a person can do about it: read why ATLAS flagged it, pick
 * the owner, create the action. ATLAS only recommends; the action waits for its owner.
 */
export function SignalDrawer({ signal, tracked, onClose, onOpenTracker }: SignalDrawerProps) {
  const t = useT();
  const addAction = useActionsStore((state) => state.addAction);
  const [ownerFor, setOwnerFor] = useState<{ id: string; owner: string } | null>(null);
  const owner = signal && ownerFor?.id === signal.id ? ownerFor.owner : signal?.action.ownerRole;

  const create = () => {
    if (!signal || !owner) return;
    const created = addAction({ ...signal.action, ownerRole: owner });
    toast.success(`${created.id}: ${t("Action created for")} ${t(owner)}`);
  };

  return (
    <DetailDrawer
      open={signal !== null}
      onOpenChange={(next) => !next && onClose()}
      title={signal ? t(signal.title) : ""}
      description={signal ? `${t(SIGNAL_MODULES[signal.module].label)} · ${signal.projectId}` : undefined}
      badges={
        signal && (
          <>
            <KindChip kind={signal.kind} />
            <TagChips tags={signal.tags} />
            <LevelChip level={signal.level} />
          </>
        )
      }
    >
      {signal && (
        <>
          <p className="flex items-start gap-2 rounded-lg bg-primary-50 px-3 py-2.5 text-sm text-primary-950">
            <Sparkles size={16} aria-hidden className="mt-0.5 shrink-0 text-primary-700" />
            <span>
              <Tr>Generated by ATLAS from the governed demo data.</Tr>
              {signal.estimated && (
                <>
                  {" "}
                  <strong><Tr>This figure is ATLAS-estimated.</Tr></strong>
                </>
              )}
            </span>
          </p>

          <DrawerSection title="Why ATLAS flagged this">
            <ReasonText text={signal.summary} className="text-sm leading-relaxed text-gray-900" />
            <dl className="grid grid-cols-2 gap-3">
              {signal.metrics.map((metric) => (
                <div key={metric.label} className="rounded-lg border border-border px-3 py-2.5">
                  <dt className="text-xs text-gray-600"><Tr>{metric.label}</Tr></dt>
                  <dd className="mt-0.5 text-lg font-semibold tabular-nums text-gray-950"><Tr>{metric.value}</Tr></dd>
                </div>
              ))}
            </dl>
            {!isListedInReason(signal.summary, signal.evidence) && (
              <ul className="list-disc space-y-1.5 pl-5 text-sm leading-relaxed text-gray-800">
                {signal.evidence.map((line) => (
                  <li key={line}><Tr>{line}</Tr></li>
                ))}
              </ul>
            )}
          </DrawerSection>

          <DrawerSection title="What this rests on">
            <ul className="flex flex-wrap gap-1.5">
              {signal.basis.map((item) => (
                <li key={item}>
                  <Chip className="bg-gray-50 text-gray-800 ring-gray-200"><Tr>{item}</Tr></Chip>
                </li>
              ))}
            </ul>
          </DrawerSection>

          <DrawerSection title="Suggested action">
            <div className="space-y-2 rounded-xl border border-primary-200 bg-primary-50/50 p-4">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <Chip className="bg-white text-primary-900 ring-primary-200">
                  <UserCheck size={12} aria-hidden />
                  <Tr>A person approves</Tr>
                </Chip>
                <span className="text-xs text-gray-700">
                  <Tr>{AUTONOMY_LABELS[signal.action.autonomy]}</Tr>
                </span>
              </div>
              <p className="text-sm font-semibold leading-snug text-gray-950"><Tr>{signal.action.title}</Tr></p>
              <p className="text-xs text-gray-700">
                <Tr>Owner</Tr> <Tr>{signal.action.ownerRole}</Tr> · <Tr>due</Tr> {formatDate(signal.action.dueDate)}
              </p>
            </div>
          </DrawerSection>

          <DrawerSection title="Take action">
            {tracked ? (
              <div className="space-y-3 rounded-xl border border-green-200 bg-green-50 p-4" role="status">
                <p className="flex items-center gap-2 text-sm font-semibold text-green-900">
                  <CircleCheck size={16} aria-hidden />
                  <Tr>Tracked as</Tr> {tracked.id}
                </p>
                <p className="text-sm text-green-950">
                  <Tr>Owner</Tr> <Tr>{tracked.ownerRole}</Tr> · <Tr>due</Tr> {formatDate(tracked.dueDate)}
                </p>
                <Button
                  type="button"
                  variant="outline"
                  className="bg-white"
                  onClick={() => {
                    onClose();
                    onOpenTracker();
                  }}
                >
                  <Tr>View in the action tracker</Tr>
                  <ArrowRight size={16} aria-hidden />
                </Button>
              </div>
            ) : (
              <div className="space-y-3">
                <div className="space-y-1.5">
                  <label htmlFor="signal-owner" className="text-sm font-medium text-gray-900">
                    <Tr>Owner of the action</Tr>
                  </label>
                  <select
                    id="signal-owner"
                    value={owner}
                    onChange={(event) => setOwnerFor({ id: signal.id, owner: event.target.value })}
                    className="h-10 w-full cursor-pointer rounded-lg border border-border bg-background px-3 text-sm focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary-400"
                  >
                    {OWNER_ROLES.map((role) => (
                      <option key={role} value={role}>
                        {t(role)}
                      </option>
                    ))}
                  </select>
                </div>
                <Button type="button" onClick={create} className="h-11 w-full bg-primary-700 text-base text-white hover:bg-primary-800">
                  <Check size={16} aria-hidden />
                  <Tr>Create action</Tr>
                </Button>
                <p className="text-xs leading-relaxed text-gray-700">
                  <Tr>Assistants never execute. Every action here is a recommendation, a draft, or a request for a named owner.</Tr>
                </p>
              </div>
            )}
          </DrawerSection>

          <DrawerSection title="Open">
            <div className="flex flex-col gap-2">
              <Link
                href={SIGNAL_MODULES[signal.module].href(signal.projectId)}
                className="inline-flex items-center justify-between gap-2 rounded-lg border border-border px-4 py-2.5 text-sm font-medium text-gray-900 hover:bg-primary-50"
              >
                <Tr>{SIGNAL_MODULES[signal.module].label}</Tr>
                <ArrowRight size={16} aria-hidden />
              </Link>
              <Link href="/ptepi/ask-atlas" className="inline-flex items-center gap-2 text-sm font-medium text-primary-800 hover:underline">
                <MessageSquareText size={16} aria-hidden />
                <Tr>Ask Nexa about this</Tr>
              </Link>
            </div>
          </DrawerSection>
        </>
      )}
    </DetailDrawer>
  );
}
