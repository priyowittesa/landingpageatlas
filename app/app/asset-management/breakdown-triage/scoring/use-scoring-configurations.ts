"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import type { AxiosError } from "axios";
import { axiosConfig } from "@/lib/axios";
import { env } from "@/lib/env";
import type { ApiResponseError } from "@/types/api";
import type { ScoringConfig } from "../lib/types";

const axios = axiosConfig(env.apiBaseUrl);
const URL = "/v1/predictive-breakdown/scoring-configurations";
const KEY = ["asset-management", "scoring-configurations"] as const;

export type ScoringStatus = "draft" | "active" | "archived";

export interface ScoringConfigurationVersion {
  id: string;
  version: number;
  status: ScoringStatus;
  /** Change note; generated by the API from the differences with the active version when left empty. */
  note: string;
  author: string;
  /** Who activated it; empty for a draft. */
  activatedBy: string;
  createdAt: string;
  activatedAt: string;
  config: ScoringConfig;
}

export type ScoringConfigurationFilters = { search?: string; status?: ScoringStatus; page_size: number; page_token?: string };

function object(value: unknown) { return (value && typeof value === "object" && !Array.isArray(value) ? value : {}) as Record<string, unknown>; }
function unwrap(value: unknown) { let current = value; for (let i = 0; i < 3; i += 1) { const row = object(current); if (!("data" in row)) break; current = row.data; } return object(current); }
function text(value: unknown, fallback = "") { if (value && typeof value === "object") { const row = object(value); return String(row.name ?? row.full_name ?? row.username ?? fallback); } return value == null || value === "" ? fallback : String(value); }
function list(value: unknown) { return Array.isArray(value) ? value : []; }
function number(value: unknown, fallback = 0) { const parsed = Number(value); return Number.isFinite(parsed) ? parsed : fallback; }

/** "02 Nov 2026", the date format the version list used before the API. */
export function formatVersionDate(value: string) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat("en-GB", { day: "2-digit", month: "short", year: "numeric" }).format(date);
}

function normalizeConfig(raw: unknown): ScoringConfig {
  const values = object(raw), weights = object(values.weights), thresholds = object(values.thresholds), targets = object(values.response_targets);
  return {
    weights: {
      criticality: number(weights.criticality),
      production: number(weights.production),
      safety: number(weights.safety),
      history: number(weights.history),
    },
    p1Threshold: number(thresholds.p1),
    p2Threshold: number(thresholds.p2),
    safetyKeywords: list(values.safety_keywords).map((keyword) => text(keyword)).filter(Boolean),
    slaMinutes: { P1: number(targets.p1_minutes), P2: number(targets.p2_minutes), P3: number(targets.p3_minutes) },
    autoEscalate: Boolean(targets.auto_escalation),
  };
}

function normalizeVersion(raw: unknown, index = 0): ScoringConfigurationVersion {
  const row = object(raw);
  return {
    id: text(row.id, String(index)),
    version: number(row.version),
    status: text(row.status, "draft").toLowerCase() as ScoringStatus,
    note: text(row.change_note ?? row.note),
    author: text(row.created_by_name ?? row.created_by ?? row.author, "—"),
    activatedBy: text(row.activated_by_name ?? row.activated_by ?? row.approved_by_name ?? row.approved_by),
    createdAt: text(row.created_at),
    activatedAt: text(row.activated_at),
    config: normalizeConfig(row.values ?? row.config ?? row),
  };
}

/** API body of a version's values; the inverse of `normalizeConfig`. */
export function configValues(config: ScoringConfig) {
  return {
    weights: { ...config.weights },
    thresholds: { p1: config.p1Threshold, p2: config.p2Threshold },
    response_targets: {
      p1_minutes: config.slaMinutes.P1,
      p2_minutes: config.slaMinutes.P2,
      p3_minutes: config.slaMinutes.P3,
      auto_escalation: config.autoEscalate,
    },
    safety_keywords: [...config.safetyKeywords],
  };
}

export function useScoringConfigurations(filters: ScoringConfigurationFilters) {
  return useQuery<
    { items: ScoringConfigurationVersion[]; statusCounts: Partial<Record<ScoringStatus, number>>; nextPageToken: string; totalCount: number },
    AxiosError<ApiResponseError>
  >({
    queryKey: [...KEY, "list", filters],
    queryFn: async () => {
      const body = unwrap((await axios.get(URL, { params: filters })).data);
      const counts = object(body.status_counts);
      return {
        items: list(body.items ?? body.configurations ?? body.results).map(normalizeVersion),
        statusCounts: Object.fromEntries(Object.entries(counts).map(([key, value]) => [key.toLowerCase(), number(value)])),
        nextPageToken: text(body.next_page_token ?? body.nextPageToken),
        totalCount: number(body.total_count ?? body.totalCount),
      };
    },
    placeholderData: (previous) => previous,
    refetchOnWindowFocus: false,
    meta: { errorMessage: "Failed to load scoring versions" },
  });
}

/** The version triage uses right now; `null` while no version was ever activated (404). */
export function useActiveScoringConfiguration() {
  return useQuery<ScoringConfigurationVersion | null, AxiosError<ApiResponseError>>({
    queryKey: [...KEY, "active"],
    queryFn: async () => {
      try {
        return normalizeVersion(unwrap((await axios.get(`${URL}/active`)).data));
      } catch (error) {
        if ((error as AxiosError).response?.status === 404) return null;
        throw error;
      }
    },
    refetchOnWindowFocus: false,
    meta: { errorMessage: "Failed to load the active scoring version", suppressErrorStatuses: [404] },
  });
}

export function useScoringConfiguration(id: string | undefined) {
  return useQuery<ScoringConfigurationVersion, AxiosError<ApiResponseError>>({
    queryKey: [...KEY, "detail", id],
    enabled: Boolean(id),
    queryFn: async () => normalizeVersion(unwrap((await axios.get(`${URL}/${id}`)).data)),
    refetchOnWindowFocus: false,
    meta: { errorMessage: "Failed to load scoring version" },
  });
}

function useScoringMutation<T>(mutationFn: (variables: T) => Promise<unknown>, errorMessage: string, successMessage?: string) {
  const client = useQueryClient();
  return useMutation<ScoringConfigurationVersion | null, AxiosError<ApiResponseError>, T>({
    mutationFn: async (variables) => {
      const body = unwrap(await mutationFn(variables));
      return Object.keys(body).length ? normalizeVersion(body) : null;
    },
    onSuccess: () => client.invalidateQueries({ queryKey: KEY }),
    meta: { errorMessage, successMessage },
  });
}

/** Starts the tenant's only draft; without `config` the API copies the active version. */
export function useCreateScoringDraft() {
  return useScoringMutation<{ config?: ScoringConfig; changeNote?: string }>(
    async ({ config, changeNote }) => (await axios.post(URL, { values: config ? configValues(config) : undefined, change_note: changeNote || undefined })).data,
    "Failed to create draft"
  );
}
export function useUpdateScoringDraft() {
  return useScoringMutation<{ id: string; config: ScoringConfig }>(
    async ({ id, config }) => (await axios.put(`${URL}/${id}`, { values: configValues(config) })).data,
    "Failed to save draft"
  );
}
export function useDeleteScoringDraft() {
  return useScoringMutation<string>(async (id) => (await axios.delete(`${URL}/${id}`)).data, "Failed to delete draft");
}
export function useActivateScoringDraft() {
  return useScoringMutation<string>(async (id) => (await axios.post(`${URL}/${id}/activate`)).data, "Failed to activate version");
}
/** Copies an archived version into a new version and activates it right away. */
export function useRollbackScoringConfiguration() {
  return useScoringMutation<number>(async (version) => (await axios.post(`${URL}/rollback`, { version })).data, "Failed to activate version");
}
